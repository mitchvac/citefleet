test("encodeQr reproduces the reference symbols exactly", () => {
  assert.equal(FIXTURES.length, 4, "positive control: fixtures loaded");
  for (const fixture of FIXTURES) {
    const qr = encodeQr(fixture.text);
    assert.equal(qr.version, fixture.version, `version for ${fixture.text.slice(0, 24)}`);
    assert.equal(qr.size, fixture.rows.length, "module count per side");
    const rendered = qr.modules.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""));
    assert.deepEqual(rendered, fixture.rows, `matrix for ${fixture.text.slice(0, 24)}`);
  }
});

test("negative control: a single flipped module fails the comparison", () => {
  const qr = encodeQr(FIXTURES[0].text);
  const rendered = qr.modules.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""));
  const broken = [...rendered];
  broken[10] = broken[10].slice(0, 9) + (broken[10][9] === "1" ? "0" : "1") + broken[10].slice(10);
  assert.notDeepEqual(broken, FIXTURES[0].rows);
});

test("payload limits: empty throws, 213 bytes fits version 10, 214 throws", () => {
  assert.throws(() => encodeQr(""), /empty/);
  assert.equal(encodeQr("x".repeat(213)).version, 10);
  assert.throws(() => encodeQr("x".repeat(214)), /too long/);
});

test("qrSvgPath draws one box per dark module inside the quiet zone", () => {
  const qr = encodeQr("A");
  const path = qrSvgPath(qr, 2);
  const boxes = path.match(/M/g)?.length ?? 0;
  const dark = qr.modules.flat().filter(Boolean).length;
  assert.equal(boxes, dark);
  assert.ok(dark > 0, "positive control: the symbol has dark modules");
  for (const match of path.matchAll(/M(\d+) (\d+)h1v1h-1z/g)) {
    assert.ok(Number(match[1]) >= 2 && Number(match[1]) <= qr.size + 1, `x ${match[1]} in range`);
    assert.ok(Number(match[2]) >= 2 && Number(match[2]) <= qr.size + 1, `y ${match[2]} in range`);
  }
});
